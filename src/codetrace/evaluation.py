"""Versioned fixture evaluation; structural metrics never imply semantic accuracy."""
import argparse
import asyncio
from collections import Counter
from datetime import datetime, timezone
import hashlib
import json
import os
from pathlib import Path
from uuid import uuid4

from dotenv import load_dotenv
from pydantic import BaseModel, ConfigDict, Field

from codetrace.graph import analyse
from codetrace.models import DemoModel, OpenAICompatibleModel
from codetrace.records import write_json
from codetrace.repository import Repository

CATEGORIES = {"entry", "cross-file", "config", "exception", "no-answer"}
DEFAULT_DATASET = Path(__file__).resolve().parents[2] / "examples/evaluation.json"


class Strict(BaseModel):
    model_config = ConfigDict(extra="forbid", strict=True)


class Snippet(Strict):
    path: str
    start: int = Field(ge=1)
    end: int = Field(ge=1)
    text: str = Field(min_length=1)


class Case(Strict):
    id: str = Field(pattern=r"^[a-z0-9-]+$")
    repo: str
    language: str
    manifest_sha256: str = Field(pattern=r"^[a-f0-9]{64}$")
    category: str
    question: str = Field(min_length=1, max_length=8000)
    expected_files: list[str]
    expected_facts: list[str]
    answerable: bool
    acceptable_uncertainties: list[str]
    snippets: list[Snippet]


class Dataset(Strict):
    schema_version: int
    cases: list[Case]


def manifest(root: Path) -> str:
    """Hash fixture paths and content, ignoring only Python generated bytecode."""
    items = []
    for path in sorted(root.rglob("*")):
        if "__pycache__" in path.parts or path.suffix == ".pyc":
            continue
        if path.is_symlink():
            raise ValueError("Fixture links are unsupported")
        if path.is_file():
            # Normalize checkout line endings for Windows/Linux reproducibility.
            content = path.read_bytes().replace(b"\r\n", b"\n")
            items.append([path.relative_to(root).as_posix(), hashlib.sha256(content).hexdigest()])
    return hashlib.sha256(json.dumps(items, ensure_ascii=False).encode()).hexdigest()


def _inside(root, relative):
    path = (root / relative).resolve()
    if not relative or Path(relative).is_absolute() or "\\" in relative or ":" in relative or ".." in Path(relative).parts or not path.is_relative_to(root.resolve()):
        raise ValueError("Dataset path escapes fixture root")
    return path


def load_dataset(path: Path):
    raw = json.loads(path.read_text(encoding="utf-8"))
    if raw.get("schema_version") == 2:
        from codetrace.benchmark import load_benchmark
        return load_benchmark(path)
    data = Dataset.model_validate(raw)
    cases = data.cases
    if data.schema_version != 1 or len(cases) < 10 or len({c.id for c in cases}) != len(cases):
        raise ValueError("Invalid dataset version, size or duplicate IDs")
    counts = Counter(c.category for c in cases)
    languages = Counter(c.language for c in cases)
    if set(counts) != CATEGORIES or min(counts.values()) < 2 or set(languages) != {"python", "java"} or min(languages.values()) < 4:
        raise ValueError("Dataset must cover five categories and both languages")
    for case in cases:
        root = _inside(path.parent, case.repo)
        if not root.is_dir() or manifest(root) != case.manifest_sha256:
            raise ValueError(f"Fixture hash mismatch: {case.id}")
        if len(set(case.expected_files)) != len(case.expected_files):
            raise ValueError("Duplicate expected files")
        if case.answerable and (not case.expected_files or not case.expected_facts or not case.snippets):
            raise ValueError("Answerable case needs annotated evidence")
        if not case.answerable and not case.acceptable_uncertainties:
            raise ValueError("Unanswerable case needs refusal guidance")
        for file in case.expected_files:
            if not _inside(root, file).is_file():
                raise ValueError("Missing expected file")
        if set(s.path for s in case.snippets) != set(case.expected_files):
            raise ValueError("Snippet and expected-file mismatch")
        for snippet in case.snippets:
            lines = _inside(root, snippet.path).read_text(encoding="utf-8").splitlines()
            if not snippet.start <= snippet.end <= len(lines) or "\n".join(lines[snippet.start-1:snippet.end]) != snippet.text:
                raise ValueError("Annotated snippet mismatch")
    return data, hashlib.sha256(path.read_bytes().replace(b"\r\n", b"\n")).hexdigest()


def metrics(case, result):
    citations = [c for finding in result["findings"] for c in finding["citations"]]
    evidence = {e["evidence_id"]: e for e in result["evidence"]}
    valid = []
    for c in citations:
        e = evidence.get(c["evidence_id"])
        if e and e["path"] == c["path"] and e["start"] <= c["start"] <= c["end"] <= e["end"]:
            valid.append(c)
    covered = set(case.expected_files) & {c["path"] for c in valid}
    return {"expected_files_hit": len(covered), "expected_files_total": len(case.expected_files),
            "file_coverage": len(covered)/len(case.expected_files) if case.expected_files else None,
            "valid_citations": len(valid), "total_citations": len(citations),
            "citation_validity": len(valid)/len(citations) if citations else None,
            "rounds": result["rounds"], "model_attempts": result["model_attempts"],
            "tool_count": result["tool_count"], "elapsed_ms": result["elapsed_ms"], "usage": result["usage"]}


def summarize(report):
    rows = report["cases"]
    measured = [r["metrics"] for r in rows if r.get("metrics") is not None]
    reviewed = [r for r in rows if r.get("review") is not None]
    def fraction(num, den):
        return {"numerator": num, "denominator": den, "value": num/den if den else None}
    successes = 0
    for row in reviewed:
        review = row["review"]
        accepted = (row["status"] == "completed" if row["answerable"] else
                    row["status"] == "insufficient_evidence" and review["reasonable_refusal"] is True)
        successes += bool(accepted and review["semantic_correct"] and not review["omitted_facts"])
    return {"total": len(rows), "measured": len(measured), "case_errors": sum(r["status"] == "case_error" for r in rows),
            "statuses": dict(Counter(r["status"] for r in rows)),
            "file_coverage": fraction(sum(m["expected_files_hit"] for m in measured), sum(m["expected_files_total"] for m in measured)),
            "citation_validity": fraction(sum(m["valid_citations"] for m in measured), sum(m["total_citations"] for m in measured)),
            "usage_known_cases": sum(m["usage"] is not None for m in measured),
            "reviewed": len(reviewed), "semantic_review": fraction(successes, len(reviewed)),
            "live_success_rate": successes/len(rows) if report["mode"] == "live" and rows and len(reviewed) == len(rows) else None}


async def evaluate(dataset_path: Path, *, live=False, model_factory=None):
    dataset, digest = load_dataset(dataset_path)
    report = {"schema_version": 1, "report_id": uuid4().hex, "created_at": datetime.now(timezone.utc).isoformat(),
              "dataset_sha256": digest, "mode": "live" if live else "offline", "status": "completed",
              "live_status": "not_run", "cases": []}
    if live and not all(os.getenv(k) for k in ("CODETRACE_API_KEY", "CODETRACE_MODEL", "CODETRACE_BASE_URL")):
        report.update(status="not_run", reason="missing_model_configuration")
        report["summary"] = summarize(report)
        return report
    if live:
        report["live_status"] = "run"
    for case in dataset.cases:
        row = {"id": case.id, "question": case.question, "category": case.category, "language": case.language,
               "repository_sha256": case.manifest_sha256, "answerable": case.answerable,
               "expected_facts": case.expected_facts, "acceptable_uncertainties": case.acceptable_uncertainties,
               "review": None, "metrics": None}
        model = None
        try:
            if model_factory:
                model = model_factory(case)
            elif live:
                model = OpenAICompatibleModel()
            else:
                steps = [("repository_overview", {}), ("search_code", {"query": "MAX_NAME_LENGTH" if case.category == "config" else "missing_feature_123" if not case.answerable else "main"})]
                steps += [("read_file", {"path": s.path, "start": s.start, "end": s.end}) for s in case.snippets]
                model = DemoModel(steps=steps, insufficient=not case.answerable)
            result = await analyse(model, Repository(_inside(dataset_path.parent, case.repo)), case.question, mode=report["mode"])
            row.update(status=result["stop_reason"], run_id=result["run_id"], result=result, metrics=metrics(case, result))
        except Exception as exc:
            row.update(status="case_error", error_type=type(exc).__name__)
        finally:
            if model is not None and hasattr(model, "close"):
                try:
                    await model.close()
                except Exception as exc:
                    row.update(status="case_error", error_type=type(exc).__name__)
        report["cases"].append(row)
    report["summary"] = summarize(report)
    return report


class Review(Strict):
    id: str
    run_id: str
    semantic_correct: bool
    omitted_facts: list[str]
    reasonable_refusal: bool | None
    notes: str


class Reviews(Strict):
    report_id: str
    dataset_sha256: str
    reviews: list[Review]


def import_reviews(report, raw):
    review = Reviews.model_validate(raw)
    if review.report_id != report["report_id"] or review.dataset_sha256 != report["dataset_sha256"]:
        raise ValueError("Review belongs to another report/dataset")
    rows = {row["id"]: row for row in report["cases"]}
    seen = set()
    for item in review.reviews:
        if item.id in seen or item.id not in rows or rows[item.id].get("run_id") != item.run_id:
            raise ValueError("Invalid review case/run identity")
        seen.add(item.id)
    for item in review.reviews:
        rows[item.id]["review"] = item.model_dump()
    report["summary"] = summarize(report)
    return report


def save_report(report, output):
    directory = output / report["report_id"]
    for row in report["cases"]:
        if "result" in row:
            write_json(directory / f"{row['run_id']}.json", row["result"])
    path = write_json(directory / "report.json", report)
    lines = ["# CodeTrace evaluation", "", f"Mode: **{report['mode']}**; status: {report['status']}; live: {report['live_status']}",
             "", "Offline responses are scripted; citation validity is not semantic accuracy.",
             "", f"Report: `{report['report_id']}`; dataset: `{report['dataset_sha256']}`", "",
             "| Case | Status | File coverage | Citation validity | Human semantic correct |", "| --- | --- | --- | --- | --- |"]
    for row in report["cases"]:
        m = row.get("metrics") or {}
        lines.append(f"| {row['id']} | {row['status']} | {m.get('file_coverage')} | {m.get('citation_validity')} | {(row.get('review') or {}).get('semantic_correct')} |")
    lines += ["", "Summary (null = unknown / no denominator):", "", "```json", json.dumps(report["summary"], indent=2), "```", ""]
    (directory / "report.md").write_text("\n".join(lines), encoding="utf-8")
    return path


def main():
    import sys
    # Preserve the v1 entry point, dispatch explicit v2 input to its own protocol.
    if "--dataset" in sys.argv:
        position = sys.argv.index("--dataset") + 1
        if position < len(sys.argv):
            try:
                version = json.loads(Path(sys.argv[position]).read_text(encoding="utf-8-sig")).get("schema_version")
            except (OSError, ValueError):
                version = None
            if version == 2:
                from codetrace.paired_evaluation import main as paired_main
                return paired_main()
    parser = argparse.ArgumentParser(description="CodeTrace evaluation: offline by default")
    parser.add_argument("--dataset", type=Path, default=DEFAULT_DATASET)
    parser.add_argument("--live", action="store_true")
    parser.add_argument("--output", type=Path, default=Path("runs/evaluation"))
    parser.add_argument("--report", type=Path, help="Existing report for review import (no model calls)")
    parser.add_argument("--review", type=Path, help="Human review JSON bound to report and run IDs")
    args = parser.parse_args()
    try:
        if args.report or args.review:
            if not (args.report and args.review) or args.live:
                raise ValueError("Use --report and --review together without --live")
            report = import_reviews(json.loads(args.report.read_text(encoding="utf-8")), json.loads(args.review.read_text(encoding="utf-8")))
        else:
            if args.live:
                load_dotenv(Path.cwd() / ".env", override=False)
            report = asyncio.run(evaluate(args.dataset, live=args.live))
        target = save_report(report, args.output)
        print(f"{report['mode']}: {report['status']}; report: {target}")
        if report["status"] == "not_run":
            return 2
        return 0 if all(r["status"] in {"completed", "insufficient_evidence"} for r in report["cases"]) else 1
    except (ValueError, OSError):
        parser.exit(2, "Evaluation failed: invalid dataset/review or inaccessible files. No comparable score generated.\n")


if __name__ == "__main__":
    raise SystemExit(main())
